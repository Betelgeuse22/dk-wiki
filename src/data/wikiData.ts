export interface Character {
  id: string;
  name: string;
  role: string;
  tier: string;
  status: string;
  color: string;
  accentColor: string;
  avatarIcon: string; // identifier for SVG rendering
  bio: string;
  quote: string;
}

export interface Ending {
  id: string;
  title: string;
  type: 'good' | 'bad' | 'secret' | 'true';
  tag: string;
  condition: string;
  description: string;
  warningNote?: string;
}

export interface GalleryItem {
  id: string;
  title: string;
  category: string;
  status: string;
  description: string;
  aspect: string;
  gradient: string;
  iconName: string;
}

export interface FactItem {
  id: number;
  title: string;
  content: string;
  date?: string;
}

export interface TeamMember {
  id: string;
  name: string;
  roles: string;
  avatarText: string;
  avatarUrl?: string;
  description: string;
  badge: string;
}

